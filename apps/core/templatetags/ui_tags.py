@register.simple_tag
def icon(name, css_class=""):
    """Inline SVG icon: {% icon "grid" %}. Only names from ICONS are ever rendered."""
    body = ICONS.get(name, ICONS["circle"])
    return format_html(
        '<svg class="icon {}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" '
        'aria-hidden="true" focusable="false">{}</svg>',
        css_class,
        mark_safe(body),
    )


@register.filter
def role_tone(role):
    """Badge colour for a role value: <span class="badge badge--{{ user.role|role_tone }}">."""
    return ROLE_TONES.get(role, "neutral")


@register.filter
def get_attr(value, path):
    """Read a simple or related-object attribute for table columns."""
    for part in path.split("__"):
        value = getattr(value, part, None)
        if value is None:
            return ""
    return value


@register.filter
def add_class(field, css_class):
    widget = field.field.widget
    if isinstance(widget, forms.CheckboxInput):
        css_class = "checkbox__input"
    elif isinstance(widget, (forms.Select, forms.SelectMultiple)):
        css_class = "select"
    elif isinstance(widget, forms.Textarea):
        css_class = "textarea"
    elif isinstance(widget, forms.FileInput):
        css_class = "file-input"
    classes = widget.attrs.get("class", "").split()
    if css_class not in classes:
        classes.append(css_class)
    return field.as_widget(attrs={"class": " ".join(classes)})